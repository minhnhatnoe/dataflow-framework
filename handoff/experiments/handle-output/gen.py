#!/usr/bin/env python3
"""Generates src/tuples.rs (static) and src/variants.rs (the benchmark pipelines) of the prototype.
usage: gen.py N SEED   (N components, parents chosen by SEED)"""
import random, sys

ARITY = 16
N = int(sys.argv[1]) if len(sys.argv) > 1 else 300
SEED = int(sys.argv[2]) if len(sys.argv) > 2 else 1
here = __file__.rsplit('/', 1)[0]

# ---- tuples.rs ----
t = []
for n in range(1, ARITY + 1):
    gs = [f"T{i}" for i in range(n)]
    for k in range(n):
        t.append(f"impl<{','.join(gs)}> At<Ix<{k}>> for ({','.join(gs)},) {{ type Out = T{k}; #[inline] fn at(&self)->&T{k}{{&self.{k}}} #[inline] fn at_mut(&mut self)->&mut T{k}{{&mut self.{k}}} }}")
        pat = ','.join([f"a{i}" for i in range(k + 1)])
        left = ','.join([f"&'a T{i}" for i in range(k)])
        leftv = ''.join([f"&*a{i}," for i in range(k)])
        t.append(f"impl<{','.join(gs)}> Split<Ix<{k}>> for ({','.join(gs)},) {{ type Left<'a> = ({left}{',' if k else ''}) where Self:'a; type Child = T{k}; #[inline] fn split<'a>(&'a mut self)->(Self::Left<'a>,&'a mut T{k}) {{ let ({pat},..) = self; (({leftv}), a{k}) }} }}")
for n in range(1, ARITY):
    gs = [f"T{i}" for i in range(n)]
    tup = ','.join([f"&'a T{i}" for i in range(n)])
    for k in range(n):
        t.append(f"impl<'a,{','.join(gs)}> Take<Ix<{k}>> for ({tup},) {{ type Out = &'a T{k}; #[inline] fn take(&self)->&'a T{k}{{self.{k}}} }}")
open(f"{here}/src/tuples.rs", "w").write("// generated by gen.py\n" + "\n".join(t) + "\n")

# ---- shape ----
def cap(w):
    c = ARITY
    while c * ARITY < w:
        c *= ARITY
    return c

def path(p):
    lo, hi, ds = 0, N, []
    while True:
        if hi - lo <= ARITY:
            ds.append(p - lo); break
        c = cap(hi - lo); k = (p - lo) // c
        nh = min(lo + (k + 1) * c, hi); lo += k * c; hi = nh; ds.append(k)
    return ds

def tree(lo, hi, f):
    if hi - lo <= ARITY:
        return "(" + "".join(f(i) + "," for i in range(lo, hi)) + ")"
    c = cap(hi - lo)
    out = []
    a = lo
    while a < hi:
        b = min(a + c, hi); out.append(tree(a, b, f)); a = b
    return "(" + ",".join(out) + ",)"

def at(base, p, mut=False):
    e = base
    for d in path(p):
        e = f"At::<Ix<{d}>>::{'at_mut' if mut else 'at'}({'&mut ' if mut and e==base else ''}{e if e!=base else ('*'+e if False else e)})"
    return e

# ---- topology ----
rnd = random.Random(SEED)
WIDE = N // 2
parents = []
for i in range(N):
    if i == WIDE:
        ps = [rnd.randrange(-1, i) for _ in range(30)]
    elif i == 7 and i > 3:
        ps = [3, 3, -1]          # alias: the same parent listed twice
    else:
        k = rnd.choice([2, 2, 3])
        ps = [rnd.randrange(max(-1, i - 40) if rnd.random() < 0.8 else -1, i) for _ in range(k)]
    parents.append(ps)
kinds_h = ['h'] * N
kinds_v = ['v'] * N
r2 = random.Random(SEED + 1)
kinds_m = [r2.choice('vho') for _ in range(N)]

def ty_state(k): return {"v":"CV","h":"CH","o":"CO"}[k]
def ty_out(k): return "u64" if k == 'v' else "u32"
def init_state(i, k): return f"CV{{acc:{i}}}" if k == 'v' else f"{ty_state(k)}{{arr:[{i},0,0,0]}}"
kinds_o = ['o'] * N
def init_out(k): return "0" if k == 'v' else "0"

o = []
o.append("// generated by gen.py\nuse crate::*;\n")
o.append("""
pub struct CV { pub acc: u64 }
pub struct CH { pub arr: [u64; 4] }
pub struct CO { pub arr: [u64; 4] }
impl HandleComponent for CO {
    type Handle = u32;
    type Output<'a> = u64;
    #[inline(always)] fn output<'a>(&'a self, h: &'a u32) -> u64 { self.arr[(*h & 3) as usize] }
}
impl HandleComponent for CH {
    type Handle = u32;
    type Output<'a> = &'a u64;
    #[inline(always)] fn output<'a>(&'a self, h: &'a u32) -> &'a u64 { &self.arr[(*h & 3) as usize] }
}
#[inline(always)] fn mix<const K: usize>(mut s: u64, ins: [u64; K]) -> u64 { for x in ins { s = s.wrapping_mul(31).wrapping_add(x); } s }
#[inline(always)] fn upd_v<const K: usize>(me: &mut CV, ins: [u64; K]) -> u64 { let s = mix(me.acc, ins); me.acc = s; s }
#[inline(always)] fn upd_h<const K: usize>(me: &mut CH, ins: [u64; K]) -> u32 { let s = mix(me.arr[0], ins); let i = (s & 3) as u32; me.arr[i as usize] = s; i }
#[inline(always)] fn upd_o<const K: usize>(me: &mut CO, ins: [u64; K]) -> u32 { let s = mix(me.arr[0], ins); let i = (s & 3) as u32; me.arr[i as usize] = s; i }
""")

def variant(name, kinds):
    S = tree(0, N, lambda i: ty_state(kinds[i]))
    O = tree(0, N, lambda i: ty_out(kinds[i]))
    o.append(f"pub struct {name} {{ pub st: {S}, pub outs: {O} }}")
    o.append(f"impl {name} {{ pub fn new() -> Self {{ {name} {{ st: {tree(0,N,lambda i: init_state(i,kinds[i]))}, outs: {tree(0,N,lambda i: init_out(kinds[i]))} }} }}")
    o.append(f"  pub fn sum(&self) -> u64 {{ let mut s = 0u64;")
    for i in range(N):
        if kinds[i] == 'v':
            s = f"*{rd_out('self.outs', i)}"
        else:
            s = f"*At::<Ix<{path(i)[-1]}>>::at(&0u8).max_dummy()" if False else None
        if kinds[i] == 'v':
            o.append(f"    s = s.wrapping_add({s});")
        else:
            o.append(f"    s = s.wrapping_add({'*' if kinds[i]=='h' else ''}{ty_state(kinds[i])}::output({rd_state('&self.st', i)}, {rd_out('self.outs', i)}));")
    o.append("  s }")
    o.append(f"  #[inline(never)] pub fn push(&mut self, x: u64) {{ let st = &mut self.st; let outs = &mut self.outs; let root = &x;")
    for i in range(N):
        k = kinds[i]
        has_h = any(p >= 0 and kinds[p] != 'v' for p in parents[i])
        # reading a parent: from ctx (needs split) or outs
        def read_parent(p, ctxinfo):
            if p < 0: return "*root"
            if kinds[p] == 'v':
                return "*" + rd_out('outs', p)
            # handle parent: its state through the left context
            return f"{'*' if kinds[p]=='h' else ''}{ty_state(kinds[p])}::output({ctx_state(ctxinfo, i, p)}, {rd_out('outs', p)})"
        n = len(parents[i])
        if has_h:
            pd = path(i)
            lines = ["let (l1, x) = Split::<Ix<%d>>::split(st);" % pd[0]]
            for lv in range(1, len(pd)):
                lines.append(f"let (l{lv+1}, x) = Split::<Ix<{pd[lv]}>>::split(x);")
            # the last x is the child
            body = " ".join(lines)
            ins = ", ".join(read_parent(p, None) for p in parents[i])
            upd = f"upd_{k}(x, [{ins}])"
            o.append(f"    let r{i} = {{ {body} {upd} }};")
        else:
            ins = ", ".join(read_parent(p, None) for p in parents[i])
            sref = f"{at_mut('st', i)}"
            o.append(f"    let r{i} = upd_{k}({sref}, [{ins}]);")
        o.append(f"    *{at_mut('outs', i)} = r{i};")
    o.append("  }\n}")

def rd_out(base, i):
    e = f"&*{base}" if base == 'outs' else f"&{base}"
    for d in path(i):
        e = f"At::<Ix<{d}>>::at({e})"
    return e

def rd_state(base, i):
    e = base
    for d in path(i):
        e = f"At::<Ix<{d}>>::at({e})"
    return e

def at_mut(base, i):
    e = f"&mut *{base}"
    for d in path(i):
        e = f"At::<Ix<{d}>>::at_mut({e})"
    return e

def ctx_state(_, i, q):
    pi, pq = path(i), path(q)
    L = next(l for l in range(len(pi)) if pi[l] != pq[l])
    assert pq[L] < pi[L], (i, q)
    e = f"Take::<Ix<{pq[L]}>>::take(&l{L+1})"
    for d in pq[L + 1:]:
        e = f"At::<Ix<{d}>>::at({e})"
    return e

variant("VV", kinds_v)
variant("HH", kinds_h)
variant("OO", kinds_o)
variant("MM", kinds_m)

# ---- hand-written ----
def hand(name, kinds):
    o.append(f"pub struct {name} {{")
    for i in range(N):
        o.append(f"  pub c{i}: {ty_state(kinds[i])}, pub o{i}: {ty_out(kinds[i])},")
    o.append("}")
    o.append(f"impl {name} {{ pub fn new() -> Self {{ {name} {{")
    for i in range(N):
        o.append(f"  c{i}: {init_state(i,kinds[i])}, o{i}: {init_out(kinds[i])},")
    o.append("} }")
    o.append("  pub fn sum(&self) -> u64 { let mut s = 0u64;")
    for i in range(N):
        if kinds[i] == 'v': o.append(f"    s = s.wrapping_add(self.o{i});")
        else: o.append(f"    s = s.wrapping_add({'*' if kinds[i]=='h' else ''}{ty_state(kinds[i])}::output(&self.c{i}, &self.o{i}));")
    o.append("  s }")
    o.append("  #[inline(never)] pub fn push(&mut self, x: u64) { let root = &x;")
    for i in range(N):
        k = kinds[i]
        ins = []
        for p in parents[i]:
            if p < 0: ins.append("*root")
            elif kinds[p] == 'v': ins.append(f"self.o{p}")
            else: ins.append(f"{'*' if kinds[p]=='h' else ''}{ty_state(kinds[p])}::output(&self.c{p}, &self.o{p})")
        o.append(f"    self.o{i} = upd_{k}(&mut self.c{i}, [{', '.join(ins)}]);")
    o.append("  }\n}")

hand("HandV", kinds_v)
hand("HandH", kinds_h)
hand("HandO", kinds_o)

open(f"{here}/src/variants.rs", "w").write("\n".join(o) + "\n")
print("ok", N, "handle parents in mixed:", sum(1 for i in range(N) if any(p >= 0 and kinds_m[p] != 'v' for p in parents[i])))
