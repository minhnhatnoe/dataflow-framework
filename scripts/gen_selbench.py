#!/usr/bin/env python3
# usage: python3 scripts/gen_selbench.py [E=2] [S=4] [K=3] [packets=1000]   -> writes dataflow-flat/examples/selbench.rs
# A selector-heavy graph for the event model: a root enum `Packet { E0(Ex0Msg), .., Idle }`, each exchange payload an enum
# with one variant per symbol. For every (exchange e, symbol s) a chain of K components, the first subscribing through
# the selector chain `packet::E<e>, ex<e>_msg::S<s>`; per symbol a join `Best<s>` over the E exchanges' chains
# (exclusive branches); one `Sink` over all joins. A deterministic packet sequence is pre-generated; the framework is
# compared with a hand-written nested `match` that stores each output in a field. Both sides must agree.
import os, sys
args = [int(a) for a in sys.argv[1:]]
E, S, K, N = (args + [2, 4, 3, 1000][len(args):])[:4]
o = ['''#![allow(non_snake_case, dead_code)]
//! Generated by scripts/gen_selbench.py: selector-heavy graph vs a hand-written nested match.
use dataflow_flat::{Component, ComponentSubscription, Configs, Demux, Pipeline, Root};
use std::hint::black_box;
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::Instant;
''']
o.append(f"const E: usize = {E}; const S: usize = {S}; const K: usize = {K};")
for e in range(E):
    o.append(f"#[derive(Clone, Copy, Demux)]\npub enum Ex{e}Msg {{ " + ", ".join(f"S{s}(u64)" for s in range(S)) + " }")
o.append("#[derive(Clone, Copy, Root, Demux)]\npub enum Packet { " + ", ".join(f"E{e}(Ex{e}Msg)" for e in range(E)) + ", Idle }")
o.append("pub static OUT: AtomicU64 = AtomicU64::new(0);")
o.append("mod flat {\n    use super::*;")
def last(e, s): return f"L{K-1}_{e}_{s}" if K > 1 else f"Book_{e}_{s}"
for e in range(E):
    for s in range(S):
        o.append(f"""    #[derive(ComponentSubscription)]
    #[subscribe(p: Packet => packet::E{e}, ex{e}_msg::S{s})]
    pub struct Book_{e}_{s}(u64);
    impl Component for Book_{e}_{s} {{
        type Config = (); type Output = u64;
        fn new((): (), _: Self::Init<'_>) -> (Self, u64) {{ (Book_{e}_{s}({e*S+s}), 0) }}
        fn update(&mut self, input: Self::Input<'_>) -> u64 {{ self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(*input.p); self.0 }}
    }}""")
        for k in range(1, K):
            prev = "Book_%d_%d" % (e, s) if k == 1 else f"L{k-1}_{e}_{s}"
            o.append(f"""    #[derive(ComponentSubscription)]
    #[subscribe(b: {prev})]
    pub struct L{k}_{e}_{s}(u64);
    impl Component for L{k}_{e}_{s} {{
        type Config = (); type Output = u64;
        fn new((): (), _: Self::Init<'_>) -> (Self, u64) {{ (L{k}_{e}_{s}({k}), 0) }}
        fn update(&mut self, input: Self::Input<'_>) -> u64 {{ self.0 = (self.0 ^ *input.b).rotate_left(5).wrapping_add({k}); self.0 }}
    }}""")
for s in range(S):
    subs = ", ".join(f"x{e}: {last(e, s)}" for e in range(E))
    body = " ^ ".join(f"input.x{e}.rotate_left({e+1})" for e in range(E))
    o.append(f"""    #[derive(ComponentSubscription)]
    #[subscribe({subs})]
    pub struct Best{s}(u64);
    impl Component for Best{s} {{
        type Config = (); type Output = u64;
        fn new((): (), _: Self::Init<'_>) -> (Self, u64) {{ (Best{s}({s}), 0) }}
        fn update(&mut self, input: Self::Input<'_>) -> u64 {{ self.0 = self.0.wrapping_add({body}); self.0 }}
    }}""")
subs = ", ".join(f"b{s}: Best{s}" for s in range(S))
body = " ^ ".join(f"input.b{s}.rotate_left({s % 63 + 1})" for s in range(S))
o.append(f"""    #[derive(ComponentSubscription)]
    #[subscribe({subs})]
    pub struct Sink;
    impl Component for Sink {{
        type Config = (); type Output = ();
        fn new((): (), _: Self::Init<'_>) -> (Self, ()) {{ (Sink, ()) }}
        fn update(&mut self, input: Self::Input<'_>) {{ OUT.store({body}, Ordering::Relaxed) }}
    }}
}}""")
# hand-written
o.append("mod hand {\n    use super::*;")
for e in range(E):
    for s in range(S):
        o.append(f"    pub struct Book_{e}_{s}(pub u64);\n    impl Book_{e}_{s} {{ #[inline] pub fn update(&mut self, p: &u64) -> u64 {{ self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(*p); self.0 }} }}")
        for k in range(1, K):
            o.append(f"    pub struct L{k}_{e}_{s}(pub u64);\n    impl L{k}_{e}_{s} {{ #[inline] pub fn update(&mut self, b: &u64) -> u64 {{ self.0 = (self.0 ^ *b).rotate_left(5).wrapping_add({k}); self.0 }} }}")
for s in range(S):
    params = ", ".join(f"x{e}: &u64" for e in range(E))
    body = " ^ ".join(f"x{e}.rotate_left({e+1})" for e in range(E))
    o.append(f"    pub struct Best{s}(pub u64);\n    impl Best{s} {{ #[inline] pub fn update(&mut self, {params}) -> u64 {{ self.0 = self.0.wrapping_add({body}); self.0 }} }}")
params = ", ".join(f"b{s}: &u64" for s in range(S))
body = " ^ ".join(f"b{s}.rotate_left({s % 63 + 1})" for s in range(S))
o.append(f"    pub struct Sink;\n    impl Sink {{ #[inline] pub fn update(&mut self, {params}) -> u64 {{ {body} }} }}")
fields = []
for e in range(E):
    for s in range(S):
        fields.append(f"Book_{e}_{s}")
        for k in range(1, K): fields.append(f"L{k}_{e}_{s}")
for s in range(S): fields.append(f"Best{s}")
o.append("    pub struct Hand {\n" + "".join(f"        pub c_{f}: {f}, pub o_{f}: u64,\n" for f in fields) + "        pub c_Sink: Sink, pub o_Sink: u64,\n    }")
def init(f):
    n = f.split("_")[0]
    return f"{f}({'0'})"
# constructors mirror `new` above
def ctor(f):
    if f.startswith("Book_"):
        _, e, s = f.split("_"); return f"{f}({int(e)*S+int(s)})"
    if f.startswith("L"):
        k = f.split("_")[0][1:]; return f"{f}({k})"
    if f.startswith("Best"): return f"{f}({f[4:]})"
o.append("    impl Hand {\n        pub fn new() -> Hand { Hand {\n" + "".join(f"            c_{f}: {ctor(f)}, o_{f}: 0,\n" for f in fields) + "            c_Sink: Sink, o_Sink: 0,\n        } }")
o.append("        #[inline(never)]\n        pub fn step(&mut self, pkt: &Packet) -> u64 {\n            match pkt {")
for e in range(E):
    o.append(f"                Packet::E{e}(m) => match m {{")
    for s in range(S):
        stmts = [f"self.o_Book_{e}_{s} = self.c_Book_{e}_{s}.update(v);"]
        for k in range(1, K):
            prev = f"Book_{e}_{s}" if k == 1 else f"L{k-1}_{e}_{s}"
            stmts.append(f"self.o_L{k}_{e}_{s} = self.c_L{k}_{e}_{s}.update(&self.o_{prev});")
        stmts.append(f"self.o_Best{s} = self.c_Best{s}.update({', '.join(f'&self.o_{last(x, s)}' for x in range(E))});")
        stmts.append("self.o_Sink = self.c_Sink.update(" + ", ".join(f"&self.o_Best{t}" for t in range(S)) + ");")
        o.append(f"                    Ex{e}Msg::S{s}(v) => {{ " + " ".join(stmts) + " }")
    o.append("                },")
o.append("                Packet::Idle => {}\n            }\n            self.o_Sink\n        }\n    }\n}")
o.append(f"""
fn packets(n: usize) -> Vec<Packet> {{
    let mut x: u64 = 0x9E3779B97F4A7C15;
    (0..n).map(|_| {{
        x ^= x << 13; x ^= x >> 7; x ^= x << 17;
        let (r, v) = ((x >> 8) as usize, x >> 20);
        match r % (16 * E * S) {{
            0..=15 => Packet::Idle,
            q => match (q / 16) % E {{
{chr(10).join(f"                {e} => Packet::E{e}(match (q / (16 * E)) % S {{ " + ", ".join(f"{s} => Ex{e}Msg::S{s}(v)" for s in range(S)) + ", _ => unreachable!() }),"
              for e in range(E))}
                _ => unreachable!(),
            }},
        }}
    }}).collect()
}}

#[inline(never)]
fn run_flat(p: &mut Pipeline<Packet, (flat::Sink,)>, pkt: Packet) -> u64 {{ p.push(pkt); OUT.load(Ordering::Relaxed) }}

const N: usize = {N};
const ROUNDS: usize = 11;
const REPS: usize = 200;
fn main() {{
    let pk = packets(N);
    let mut p = Pipeline::<Packet, (flat::Sink,)>::build(Configs::new()).unwrap();
    let mut h = hand::Hand::new();
    // The two sides must agree on every packet.
    for x in &pk {{ assert_eq!(run_flat(&mut p, *x), h.step(x)); }}
    let (mut tf, mut th) = (Vec::new(), Vec::new());
    let mut acc = 0u64;
    for r in 0..ROUNDS {{
        let mut side = |flat: bool| {{
            let t = Instant::now();
            for _ in 0..REPS {{ for x in &pk {{ acc ^= if flat {{ run_flat(&mut p, black_box(*x)) }} else {{ h.step(black_box(x)) }}; }} }}
            let ns = t.elapsed().as_nanos() as f64 / (REPS * N) as f64;
            if flat {{ tf.push(ns) }} else {{ th.push(ns) }}
        }};
        if r % 2 == 0 {{ side(true); side(false); }} else {{ side(false); side(true); }}
    }}
    black_box(acc);
    for v in [&mut tf, &mut th] {{ v.sort_by(|a, b| a.partial_cmp(b).unwrap()); }}
    println!("flat:         min {{:>6.2}}  median {{:>6.2}} ns/packet  ({{}} components)", tf[0], tf[ROUNDS / 2], p.len());
    println!("hand-written: min {{:>6.2}}  median {{:>6.2}} ns/packet", th[0], th[ROUNDS / 2]);
    println!("results agree");
}}
""")
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "dataflow-flat", "examples", "selbench.rs")
open(path, "w").write("\n".join(o))
print(f"E={E} S={S} K={K}: {E*S*K + S + 1} components")
