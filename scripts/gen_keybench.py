#!/usr/bin/env python3
# usage: python3 scripts/gen_keybench.py [E=2] [S=4] [K=3] [packets=1000]   -> writes dataflow-flat/examples/keybench.rs
# A keyed-selector graph: a root `Packet { ex, key, v }`, per exchange e a `#[listener]` component Ws<e> (output
# Option<Frame>, a Keyed value). For every (exchange e, symbol s) a chain of K components, the first subscribing through
# the selector chain `Ws<e> => Some, On<Sym<s>>`; per symbol a join `Best<s>` over the E exchanges' chains
# (E must be 1: two listeners are never known to be exclusive, so the plan rejects a join of their branches);
# the joins feed ceil(S/60) sinks `Sink<g>` (a condition has at most MAX_TERMS = 256 terms). A deterministic packet sequence is pre-generated; the framework is
# compared with a hand-written nested `match` that stores each output in a field. Both sides must agree.
import os, sys
args = [int(a) for a in sys.argv[1:]]
E, S, K, N = (args + [1, 4, 3, 1000][len(args):])[:4]
assert E == 1, 'E must be 1'
G = (S + 59) // 60
group = lambda g: range(g * 60, min(S, g * 60 + 60))
SINKS = ', '.join(f'flat::Sink{g}' for g in range(G))
o = ['''#![allow(non_snake_case, dead_code)]
//! Generated by scripts/gen_keybench.py: selector-heavy graph vs a hand-written nested match.
use dataflow_flat::{Component, ComponentSubscription, Configs, Keyed, Listener, On, Pipeline, Root, Symbol};
use std::hint::black_box;
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::Instant;
''']
o.append(f"const E: usize = {E}; const S: usize = {S}; const K: usize = {K};")
o.append("#[derive(Clone, Copy, Root)]\npub struct Packet { pub ex: u32, pub key: u32, pub v: u64 }")
o.append("#[derive(Clone, Copy)]\npub struct Frame { key: u32, v: u64 }\nimpl Keyed for Frame { type Item = u64; fn key(&self) -> Option<u32> { Some(self.key) } fn item(&self) -> &u64 { &self.v } }")
for s_ in range(S):
    o.append(f"pub struct Sym{s_}; impl Symbol for Sym{s_} {{ const KEY: u32 = {s_}; const NAME: &'static str = \"Sym{s_}\"; }}")
o.append("pub static REQUESTED: AtomicU64 = AtomicU64::new(0);")
o.append("pub static OUT: AtomicU64 = AtomicU64::new(0);")
o.append("mod flat {\n    use super::*;")
for e in range(E):
    o.append(f"""    #[derive(ComponentSubscription)]
    #[subscribe(p: Packet)]
    #[listener]
    pub struct Ws{e};
    impl Listener for Ws{e} {{ fn subscribe(&mut self, keys: &[u32]) {{ REQUESTED.fetch_add(keys.len() as u64, Ordering::Relaxed); }} }}
    impl Component for Ws{e} {{
        type Config = (); type Output = Option<Frame>;
        fn new((): (), _: Self::Init<'_>) -> (Self, Option<Frame>) {{ (Ws{e}, None) }}
        fn update(&mut self, input: Self::Input<'_>) -> Option<Frame> {{ if input.p.ex == {e} {{ Some(Frame {{ key: input.p.key, v: input.p.v }}) }} else {{ None }} }}
    }}""")
def last(e, s): return f"L{K-1}_{e}_{s}" if K > 1 else f"Book_{e}_{s}"
for e in range(E):
    for s in range(S):
        o.append(f"""    #[derive(ComponentSubscription)]
    #[subscribe(p: Ws{e} => Some, On<Sym{s}>)]
    pub struct Book_{e}_{s}(u64);
    impl Component for Book_{e}_{s} {{
        type Config = (); type Output = u64;
        fn new((): (), _: Self::Init<'_>) -> (Self, u64) {{ (Book_{e}_{s}({e*S+s}), 0) }}
        fn update(&mut self, input: Self::Input<'_>) -> u64 {{ self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(*input.p); self.0 }}
    }}""")
        for k in range(1, K):
            prev = "Book_%d_%d" % (e, s) if k == 1 else f"L{k-1}_{e}_{s}"
            o.append(f"""    #[derive(ComponentSubscription)]
    #[subscribe(b: {prev})]
    pub struct L{k}_{e}_{s}(u64);
    impl Component for L{k}_{e}_{s} {{
        type Config = (); type Output = u64;
        fn new((): (), _: Self::Init<'_>) -> (Self, u64) {{ (L{k}_{e}_{s}({k}), 0) }}
        fn update(&mut self, input: Self::Input<'_>) -> u64 {{ self.0 = (self.0 ^ *input.b).rotate_left(5).wrapping_add({k}); self.0 }}
    }}""")
for s in range(S):
    subs = ", ".join(f"x{e}: {last(e, s)}" for e in range(E))
    body = " ^ ".join(f"input.x{e}.rotate_left({e+1})" for e in range(E))
    o.append(f"""    #[derive(ComponentSubscription)]
    #[subscribe({subs})]
    pub struct Best{s}(u64);
    impl Component for Best{s} {{
        type Config = (); type Output = u64;
        fn new((): (), _: Self::Init<'_>) -> (Self, u64) {{ (Best{s}({s}), 0) }}
        fn update(&mut self, input: Self::Input<'_>) -> u64 {{ self.0 = self.0.wrapping_add({body}); self.0 }}
    }}""")
for g in range(G):
    subs = ", ".join(f"b{s}: Best{s}" for s in group(g))
    body = " ^ ".join(f"input.b{s}.rotate_left({s % 63 + 1})" for s in group(g))
    o.append(f"""    #[derive(ComponentSubscription)]
    #[subscribe({subs})]
    pub struct Sink{g};
    impl Component for Sink{g} {{
        type Config = (); type Output = ();
        fn new((): (), _: Self::Init<'_>) -> (Self, ()) {{ (Sink{g}, ()) }}
        fn update(&mut self, input: Self::Input<'_>) {{ OUT.store({body}, Ordering::Relaxed) }}
    }}""")
o.append("}")
# hand-written
o.append("mod hand {\n    use super::*;")
for e in range(E):
    for s in range(S):
        o.append(f"    pub struct Book_{e}_{s}(pub u64);\n    impl Book_{e}_{s} {{ #[inline] pub fn update(&mut self, p: &u64) -> u64 {{ self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(*p); self.0 }} }}")
        for k in range(1, K):
            o.append(f"    pub struct L{k}_{e}_{s}(pub u64);\n    impl L{k}_{e}_{s} {{ #[inline] pub fn update(&mut self, b: &u64) -> u64 {{ self.0 = (self.0 ^ *b).rotate_left(5).wrapping_add({k}); self.0 }} }}")
for s in range(S):
    params = ", ".join(f"x{e}: &u64" for e in range(E))
    body = " ^ ".join(f"x{e}.rotate_left({e+1})" for e in range(E))
    o.append(f"    pub struct Best{s}(pub u64);\n    impl Best{s} {{ #[inline] pub fn update(&mut self, {params}) -> u64 {{ self.0 = self.0.wrapping_add({body}); self.0 }} }}")
for g in range(G):
    params = ", ".join(f"b{s}: &u64" for s in group(g))
    body = " ^ ".join(f"b{s}.rotate_left({s % 63 + 1})" for s in group(g))
    o.append(f"    pub struct Sink{g};\n    impl Sink{g} {{ #[inline] pub fn update(&mut self, {params}) -> u64 {{ {body} }} }}")
fields = []
for e in range(E):
    for s in range(S):
        fields.append(f"Book_{e}_{s}")
        for k in range(1, K): fields.append(f"L{k}_{e}_{s}")
for s in range(S): fields.append(f"Best{s}")
o.append("    pub struct Hand {\n" + "".join(f"        pub c_{f}: {f}, pub o_{f}: u64,\n" for f in fields) + "        pub out: u64,\n    }")
def init(f):
    n = f.split("_")[0]
    return f"{f}({'0'})"
# constructors mirror `new` above
def ctor(f):
    if f.startswith("Book_"):
        _, e, s = f.split("_"); return f"{f}({int(e)*S+int(s)})"
    if f.startswith("L"):
        k = f.split("_")[0][1:]; return f"{f}({k})"
    if f.startswith("Best"): return f"{f}({f[4:]})"
o.append("    impl Hand {\n        pub fn new() -> Hand { Hand {\n" + "".join(f"            c_{f}: {ctor(f)}, o_{f}: 0,\n" for f in fields) + "            out: 0,\n        } }")
o.append("        #[inline(never)]\n        pub fn step(&mut self, pkt: &Packet) -> u64 {\n            match pkt.ex {")
for e in range(E):
    o.append(f"                {e} => match pkt.key {{")
    for s in range(S):
        stmts = [f"self.o_Book_{e}_{s} = self.c_Book_{e}_{s}.update(v);"]
        for k in range(1, K):
            prev = f"Book_{e}_{s}" if k == 1 else f"L{k-1}_{e}_{s}"
            stmts.append(f"self.o_L{k}_{e}_{s} = self.c_L{k}_{e}_{s}.update(&self.o_{prev});")
        stmts.append(f"self.o_Best{s} = self.c_Best{s}.update({', '.join(f'&self.o_{last(x, s)}' for x in range(E))});")
        g = s // 60
        stmts.append(f"self.out = Sink{g}.update(" + ", ".join(f"&self.o_Best{t}" for t in group(g)) + ");")
        o.append(f"                    {s} => {{ let v = &pkt.v; " + " ".join(stmts) + " }")
    o.append("                    _ => {}\n                },")
o.append("                _ => {}\n            }\n            self.out\n        }\n    }\n}")
o.append(f"""
fn packets(n: usize) -> Vec<Packet> {{
    let mut x: u64 = 0x9E3779B97F4A7C15;
    (0..n).map(|_| {{
        x ^= x << 13; x ^= x >> 7; x ^= x << 17;
        let (r, v) = ((x >> 8) as usize, x >> 20);
        // One in 16 is for a symbol nobody reads (and some for no exchange).
        if r % 16 == 0 {{ Packet {{ ex: (r / 16 % (E + 1)) as u32, key: (S + 5) as u32, v }} }}
        else {{ Packet {{ ex: (r / 16 % E) as u32, key: (r / (16 * E) % S) as u32, v }} }}
    }}).collect()
}}

#[inline(never)]
fn run_flat(p: &mut Pipeline<Packet, ({SINKS},)>, pkt: Packet) -> u64 {{ p.push(pkt); OUT.load(Ordering::Relaxed) }}

const N: usize = {N};
const ROUNDS: usize = 11;
const REPS: usize = 200;
fn main() {{
    let pk = packets(N);
    let mut p = Pipeline::<Packet, ({SINKS},)>::build(Configs::new()).unwrap();
    let mut h = hand::Hand::new();
    // The two sides must agree on every packet.
    for x in &pk {{ assert_eq!(run_flat(&mut p, *x), h.step(x)); }}
    let (mut tf, mut th) = (Vec::new(), Vec::new());
    let mut acc = 0u64;
    for r in 0..ROUNDS {{
        let mut side = |flat: bool| {{
            let t = Instant::now();
            for _ in 0..REPS {{ for x in &pk {{ acc ^= if flat {{ run_flat(&mut p, black_box(*x)) }} else {{ h.step(black_box(x)) }}; }} }}
            let ns = t.elapsed().as_nanos() as f64 / (REPS * N) as f64;
            if flat {{ tf.push(ns) }} else {{ th.push(ns) }}
        }};
        if r % 2 == 0 {{ side(true); side(false); }} else {{ side(false); side(true); }}
    }}
    black_box(acc);
    for v in [&mut tf, &mut th] {{ v.sort_by(|a, b| a.partial_cmp(b).unwrap()); }}
    println!("flat:         min {{:>6.2}}  median {{:>6.2}} ns/packet  ({{}} components)", tf[0], tf[ROUNDS / 2], p.len());
    println!("hand-written: min {{:>6.2}}  median {{:>6.2}} ns/packet", th[0], th[ROUNDS / 2]);
    println!("results agree; listeners were asked for {{}} keys in total", REQUESTED.load(Ordering::Relaxed));
}}
""")
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "dataflow-flat", "examples", "keybench.rs")
open(path, "w").write("\n".join(o))
print(f"E={E} S={S} K={K}: {E*S*K + S + 1} components")
