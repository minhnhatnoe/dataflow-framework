/// What a component subscribes to. Generated by
/// `#[derive(ComponentSubscription)]` from `#[subscribe(name: Type, ...)]`.
pub trait ComponentSubscription: 'static {
    /// The subscriptions as a type-level list `(A, (B, ()))`, walked by the
    /// runtime. The list order is the listing order in `#[subscribe(...)]`.
    type Deps: DepList;
    /// A struct with one named reference per subscription.
    type Input<'a>;
    /// Name the runtime's nested tuple of references.
    fn input<'a>(raw: <Self::Deps as DepList>::Inputs<'a>) -> Self::Input<'a>;
}

pub use dataflow_macros::ComponentSubscription;

/// A node of the dataflow graph.
///
/// # Execution order
///
/// The order in which `update` is called is part of the contract: a
/// depth-first post-order that follows subscription listing order. For a
/// component `C` subscribing to `[D1, .., Dn]` (in `#[subscribe]` order), the
/// updates that happen during `C`'s walk come in `n` blocks followed by `C`
/// itself. Block `i` is `Di` plus everything upstream of `Di` that has not
/// already run in this `run`, itself in this same order. The blocks come in
/// listing order, so a later-listed dependency that is upstream of an earlier
/// one runs inside the earlier block. A component runs exactly once per run,
/// after everything it subscribes to. `Pipeline::order` reports the
/// *construction* order, which is the same order.
pub trait Component: ComponentSubscription + NoDependencyCycleCheck + Sized {
    /// Owned configuration passed to `new`. Components without an entry in
    /// [`Configs`] get `Default::default()`.
    type Config: Default + 'static;
    /// What `update` produces; subscribers receive `&Output`. Outputs of
    /// non-root components are dropped when `run` finishes; the root's output
    /// is returned to the caller of `run`.
    type Output: 'static;

    fn new(config: Self::Config) -> Self;

    /// Invoked once per `Pipeline::run`, after everything it subscribes to.
    fn update(&mut self, input: Self::Input<'_>) -> Self::Output;
}

// ---------------------------------------------------------------------------
// Compile-time plan
// ---------------------------------------------------------------------------
//
// Every constant here is a plain value with no references inside, apart from
// the one-level `SeqList` of already-computed constants. (A graph of nested
// `&'static` constants is hashed as a tree by incremental compilation, which
// is exponential in graph depth.)
//
// `SEQ` of a component is the order a depth-first walk from it first reaches
// each component of its upstream graph, with the parent it was reached from.
// It is built in one pass from the dependencies' `SEQ`s: walking dependency
// B after A reaches exactly B's sequence minus what A already reached, in
// the same order, because what A reached is closed under "upstream of".

/// Upper bound on components per pipeline. Compile-time memory grows with
/// MAX_COMPONENTS x (number of components), so raise it only as needed.
pub const MAX_COMPONENTS: usize = 512;
const SET_CAP: usize = MAX_COMPONENTS * 2; // power of two

/// Parent id meaning "whoever owns this dependency list"; replaced when a
/// component (or the roots) adopts the list.
const OWNER: u64 = 1;
/// Parent id of the roots list.
const ROOT: u64 = 0;

/// One component in a walk order.
#[doc(hidden)]
#[derive(Clone, Copy)]
pub struct Entry {
    id: u64,
    parent: u64,
}

/// A walk order: fixed capacity so it is a plain constant.
#[doc(hidden)]
pub struct Seq {
    len: usize,
    ids: [u64; MAX_COMPONENTS],
    parents: [u64; MAX_COMPONENTS],
}

/// Open-addressing set of ids (0 = empty slot; ids are never 0 or 1).
struct IdSet {
    slots: [u64; SET_CAP],
}

impl IdSet {
    const fn new() -> Self {
        IdSet { slots: [0; SET_CAP] }
    }
    const fn slot(&self, id: u64) -> usize {
        let mut i = (id as usize) & (SET_CAP - 1);
        while self.slots[i] != 0 && self.slots[i] != id {
            i = (i + 1) & (SET_CAP - 1);
        }
        i
    }
    const fn contains(&self, id: u64) -> bool {
        self.slots[self.slot(id)] == id
    }
    const fn insert(&mut self, id: u64) {
        let i = self.slot(id);
        self.slots[i] = id;
    }
}

impl Seq {
    const fn empty() -> Seq {
        Seq { len: 0, ids: [0; MAX_COMPONENTS], parents: [0; MAX_COMPONENTS] }
    }

    const fn push(&mut self, e: Entry) {
        if self.len == MAX_COMPONENTS {
            panic!("too many components: raise dataflow_flat::MAX_COMPONENTS");
        }
        self.ids[self.len] = e.id;
        self.parents[self.len] = e.parent;
        self.len += 1;
    }

    /// Walk `deps` in order, keeping the first time each component is
    /// reached. If `owner` is given it comes first and the direct entries
    /// are attached to it; otherwise (the roots) they get parent ROOT.
    const fn merge(owner: Option<Entry>, mut deps: &'static SeqList) -> Seq {
        let mut out = Seq::empty();
        let mut seen = [0u64; SET_CAP];
        let mut n = 0;
        let parent = match owner {
            Some(e) => {
                out.ids[0] = e.id;
                out.parents[0] = e.parent;
                n = 1;
                let mut s = (e.id as usize) & (SET_CAP - 1);
                while seen[s] != 0 {
                    s = (s + 1) & (SET_CAP - 1);
                }
                seen[s] = e.id;
                e.id
            }
            None => ROOT,
        };
        let mut direct = IdSet::new();
        while let SeqList::Cons(dep, rest) = deps {
            deps = rest;
            let head = dep.ids[0];
            if direct.contains(head) {
                panic!("a component lists the same dependency twice");
            }
            direct.insert(head);
            // The component reached so far is closed under "upstream of", so a
            // dependency that is already reached contributes nothing.
            let mut s = (head as usize) & (SET_CAP - 1);
            while seen[s] != 0 && seen[s] != head {
                s = (s + 1) & (SET_CAP - 1);
            }
            if seen[s] != 0 {
                continue;
            }
            seen[s] = head;
            if n == MAX_COMPONENTS {
                panic!("too many components: raise dataflow_flat::MAX_COMPONENTS");
            }
            out.ids[n] = head;
            out.parents[n] = parent;
            n += 1;
            let (ids, parents, len) = (&dep.ids, &dep.parents, dep.len);
            let mut i = 1;
            while i < len {
                let id = ids[i];
                let mut s = (id as usize) & (SET_CAP - 1);
                let mut v = seen[s];
                while v != 0 && v != id {
                    s = (s + 1) & (SET_CAP - 1);
                    v = seen[s];
                }
                if v == 0 {
                    seen[s] = id;
                    if n == MAX_COMPONENTS {
                        panic!("too many components: raise dataflow_flat::MAX_COMPONENTS");
                    }
                    out.ids[n] = id;
                    out.parents[n] = parents[i];
                    n += 1;
                }
                i += 1;
            }
        }
        out.len = n;
        out
    }
}

/// The `SEQ`s of a dependency list's direct entries. One level of
/// references only: each `Seq` is a plain value.
#[doc(hidden)]
pub enum SeqList {
    Nil,
    Cons(&'static Seq, &'static SeqList),
}

/// FNV-1a of the type name: a compile-time identity for each component.
/// Collisions are caught when the pipeline is built (see `ConfigPass`).
const fn component_id(s: &str) -> u64 {
    let bytes = s.as_bytes();
    let mut hash: u64 = 0xcbf29ce484222325;
    let mut i = 0;
    while i < bytes.len() {
        hash ^= bytes[i] as u64;
        hash = hash.wrapping_mul(0x100000001b3);
        i += 1;
    }
    if hash <= OWNER {
        hash + 2 // keep 0 and 1 reserved
    } else {
        hash
    }
}

/// The plan of one roots list: each component's first-reached parent, found
/// by id through an open-addressing index.
#[doc(hidden)]
pub struct Plan {
    /// id -> index + 1 (0 = empty), open addressing on `keys`.
    keys: [u64; SET_CAP],
    index: [u32; SET_CAP],
    first_parent: [u64; MAX_COMPONENTS],
    /// Components are in first-reached (depth-first pre-)order, so the
    /// storage subtree of entry `i` is the range `i..end[i]`.
    end: [u32; MAX_COMPONENTS],
}

impl Plan {
    const fn from_roots(roots: &Seq) -> Plan {
        let mut plan = Plan { keys: [0; SET_CAP], index: [0; SET_CAP], first_parent: [0; MAX_COMPONENTS], end: [0; MAX_COMPONENTS] };
        let mut i = 0;
        while i < roots.len {
            let slot = plan.slot(roots.ids[i]);
            plan.keys[slot] = roots.ids[i];
            plan.index[slot] = i as u32 + 1;
            plan.first_parent[i] = roots.parents[i];
            plan.end[i] = i as u32 + 1;
            i += 1;
        }
        // Children come after their parent: grow each parent's range, last first.
        let mut i = roots.len;
        while i > 0 {
            i -= 1;
            let p = plan.first_parent[i];
            if p != ROOT {
                let pi = plan.index_of(p);
                if plan.end[i] > plan.end[pi] {
                    plan.end[pi] = plan.end[i];
                }
            }
        }
        plan
    }

    const fn slot(&self, id: u64) -> usize {
        let mut i = (id as usize) & (SET_CAP - 1);
        while self.keys[i] != 0 && self.keys[i] != id {
            i = (i + 1) & (SET_CAP - 1);
        }
        i
    }

    const fn index_of(&self, id: u64) -> usize {
        match self.index[self.slot(id)] {
            0 => panic!("component not in plan"),
            n => n as usize - 1,
        }
    }

    const fn first_parent_of(&self, id: u64) -> u64 {
        self.first_parent[self.index_of(id)]
    }

    /// Is `top` on the first-parent chain of `id` (inclusive)? Equivalently:
    /// does the storage subtree of `top` hold `id`?
    const fn holds(&self, top: u64, id: u64) -> bool {
        let t = self.index_of(top);
        let i = self.index_of(id);
        t <= i && i < self.end[t] as usize
    }
}

/// Compile-time identity and upstream walk of a component.
#[doc(hidden)]
pub trait Described {
    const ID: u64;
    const SEQ: Seq;
}

impl<C: Component> Described for C {
    const ID: u64 = component_id(type_name::<C>());
    const SEQ: Seq =
        Seq::merge(Some(Entry { id: <C as Described>::ID, parent: OWNER }), <C::Deps as DepList>::HEADS);
}

/// The parent of an edge: a component, or `RootParent` for the roots list.
#[doc(hidden)]
pub trait Parent {
    const ID: u64;
}
impl<C: Component> Parent for C {
    const ID: u64 = <C as Described>::ID;
}
#[doc(hidden)]
pub struct RootParent;
impl Parent for RootParent {
    const ID: u64 = ROOT;
}

/// The plan for a roots list, evaluated once per list type.
#[doc(hidden)]
pub trait Planned: DepList {
    const PLAN: &'static Plan;
}
impl<L: DepList> Planned for L {
    const PLAN: &'static Plan = &Plan::from_roots(&Seq::merge(None, L::HEADS));
}

/// Per-edge constant, looked up in the plan of roots list `R`.
#[doc(hidden)]
pub struct Edge<R, P, H>(PhantomData<(R, P, H)>);
impl<R: Planned, P: Parent, H: Component> Edge<R, P, H> {
    /// True if the edge `P -> H` is where the walk first reaches `H`.
    pub const FIRST: bool = R::PLAN.first_parent_of(<H as Described>::ID) == P::ID;
}

