//! Catalogs: lists of types a `for` entry of `#[subscribe(..)]` ranges over.
//!
//! ```ignore
//! type AllSymbols = catalog![Btc, Eth, Sol];
//! #[subscribe(limits: Limits, for S in AllSymbols { Quoter<S> },
//!             for (X, S) in Product<Venues, AllSymbols> { Book<X, S> })]
//! struct Oms { .. }
//! impl<S: Symbol> UpdateHandler<Quoter<S>> for Oms { .. }
//! ```
//!
//! A catalog is a plain nested tuple of types in the shape of a subscription
//! tree (a leaf of up to 15 types, an inner node of exactly 16 subtrees; the
//! [`catalog!`](crate::catalog) macro builds one from a list), or one of the
//! combinators [`Product`], [`Concat`], [`Zip`]. Pairs are [`M<X, S>`](M).
//!
//! The derive cannot see what a catalog contains. It generates a zero-sized
//! mapper type implementing [`Map`] for the body of the `for` (`S -> Quoter<S>`),
//! and the component's subscription tree gets the segment
//! `<Catalog as MapDeps<Mapper, BASE>>::Out`: the catalog's own tree with every
//! element replaced by the entry `Sub<Quoter<S>, Hd<Quoter<S>, ()>, position, By<Owner, Quoter<S>>>`.
//! The shape stays an `ARITY`-sized tree; positions are dense per catalog, in
//! catalog order, which is the listing order.

use core::any::TypeId;
use core::marker::PhantomData;

use crate::component::{DepList, Sub};
use crate::handler::{By, Hd};
use crate::node::Vertex;

/// A pair of types: the element of a [`Product`] or a [`Zip`], and what
/// `for (X, S) in ..` destructures.
pub struct M<X, S>(PhantomData<fn() -> (X, S)>);

/// A catalog: a tree of types.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is not a catalog",
    label = "a catalog is a nested tuple of types of the subscription-tree shape (a tuple of up to 15 types, or exactly 16 sub-catalogs), `catalog![A, B, ..]`, or `Product`, `Concat`, `Zip` of catalogs",
    note = "`Zip` needs two catalogs of the same shape"
)]
pub trait Catalog: 'static {
    /// The number of elements.
    const LEN: usize;
}

/// What a `for` body makes of one element of its catalog. Generated by the derive.
#[doc(hidden)]
pub trait Map<A>: 'static {
    /// The node subscribed to for the element `A`.
    type Out: Vertex;
    /// How the entries are read: [`Unnamed`] (`for S in C { N<S> }`, one handled entry per
    /// element, not a field of `Input`) or [`Named`] (`set: for S in C { N<S> }`, a field that
    /// reads every element, see [`SetIn`](crate::SetIn)).
    type Kind: ChainFor<Self::Out>;
    /// The component whose `UpdateHandler<Out>` impl handles the entry.
    type Owner: 'static;
}

/// The selector chain an entry of a `for` has.
#[doc(hidden)]
pub trait ChainFor<N: Vertex> {
    type C: crate::select::SelectChain<N::Stored>;
}
/// An unnamed `for`: the entries are handled edges, never read in `update`.
#[doc(hidden)]
pub struct Unnamed;
impl<N: Vertex> ChainFor<N> for Unnamed {
    type C = Hd<N, ()>;
}
/// A named `for` (a set): plain edges, read in `update` through the set field.
#[doc(hidden)]
pub struct Named;
impl<N: Vertex> ChainFor<N> for Named {
    type C = ();
}

/// The subscription tree of a catalog under a mapper `F`, with positions from `B`.
#[doc(hidden)]
#[diagnostic::on_unimplemented(
    message = "`{Self}` cannot be mapped by this `for` entry",
    label = "the catalog of a `for` entry must be a catalog (see `dataflow_flat::Catalog`), and every element must have its `UpdateHandler` impl",
    note = "`for S: Bound in Catalog {{ Node<S> }}` takes the bounds `Node<S>` needs"
)]
pub trait MapDeps<F, const B: usize>: Catalog {
    type Out: DepList;
}

/// The entry for the element `A` at position `POS`: what the leaf impls below
/// put in the tree (a trait, so the arithmetic on the position sits in a bound).
#[doc(hidden)]
pub trait Ent<F, A, const POS: usize> {
    type S;
}
impl<F: Map<A>, A, const POS: usize> Ent<F, A, POS> for () {
    type S = Sub<<F as Map<A>>::Out, <<F as Map<A>>::Kind as ChainFor<<F as Map<A>>::Out>>::C, POS, By<<F as Map<A>>::Owner, <F as Map<A>>::Out>>;
}

// -- plain tuples -----------------------------------------------------------------------------------

macro_rules! tuple_leaf {
    ([$($A:ident $B:ident $i:tt)*] [$($pad:tt)*]) => {
        impl<$($A: 'static,)*> Catalog for ($($A,)*) {
            const LEN: usize = 0 $(+ { let _ = stringify!($A); 1 })*;
        }
        impl<F, const BASE: usize, $($A: 'static,)*> MapDeps<F, BASE> for ($($A,)*)
        where
            $(F: Map<$A>, (): Ent<F, $A, { BASE + $i }>,)*
        {
            type Out = ($(Sub<<F as Map<$A>>::Out, <<F as Map<$A>>::Kind as ChainFor<<F as Map<$A>>::Out>>::C, { BASE + $i }, By<<F as Map<$A>>::Owner, <F as Map<$A>>::Out>>,)*);
        }
    };
}
dataflow_macros::cat_leaf!(tuple_leaf);

macro_rules! tuple_inner {
    ([$($K:ident $L:ident $pre:tt)*]) => {
        impl<$($K: Catalog,)*> Catalog for ($($K,)*) {
            const LEN: usize = 0 $(+ <$K as Catalog>::LEN)*;
        }
        impl<F, const BASE: usize, $($K: Catalog,)*> MapDeps<F, BASE> for ($($K,)*)
        where
            $($K: MapDeps<F, { BASE + $pre }>,)*
        {
            type Out = ($(<$K as MapDeps<F, { BASE + $pre }>>::Out,)*);
        }
    };
}
dataflow_macros::cat_inner!(tuple_inner);

// -- Concat -----------------------------------------------------------------------------------------

/// The elements of `A`, then those of `B`.
pub struct Concat<A, B>(PhantomData<fn() -> (A, B)>);

impl<A: Catalog, B: Catalog> Catalog for Concat<A, B> {
    const LEN: usize = A::LEN + B::LEN;
}
impl<F, const BASE: usize, A: MapDeps<F, BASE>, B: Catalog> MapDeps<F, BASE> for Concat<A, B>
where
    B: MapDeps<F, { BASE + <A as Catalog>::LEN }>,
{
    type Out = (
        <A as MapDeps<F, BASE>>::Out,
        <B as MapDeps<F, { BASE + <A as Catalog>::LEN }>>::Out,
        (), (), (), (), (), (), (), (), (), (), (), (), (), (),
    );
}

