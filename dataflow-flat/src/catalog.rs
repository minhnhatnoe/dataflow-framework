// -- Product ----------------------------------------------------------------------------------------

/// The pairs `M<a, b>` for every `a` of `A` and every `b` of `B`, in row order
/// (`a` outermost).
pub struct Product<A, B>(PhantomData<fn() -> (A, B)>);

/// One row of a product: `M<X, b>` for every `b` of `B`.
#[doc(hidden)]
pub struct Row<X, B>(PhantomData<fn() -> (X, B)>);

