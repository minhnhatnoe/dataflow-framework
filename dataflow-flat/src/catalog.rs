macro_rules! product_leaf {
    ([$($A:ident $B:ident $i:tt)*] [$($pad:tt)*]) => {
        impl<Bc: Catalog, $($A: 'static,)*> Catalog for Product<($($A,)*), Bc> {
            const LEN: usize = 0 $(+ { let _ = stringify!($A); <Bc as Catalog>::LEN })*;
        }
        impl<F, const BASE: usize, Bc: Catalog, $($A: 'static,)*> MapDeps<F, BASE> for Product<($($A,)*), Bc>
        where
            $(Row<$A, Bc>: MapDeps<F, { BASE + $i * <Bc as Catalog>::LEN }>,)*
        {
            type Out = ($(<Row<$A, Bc> as MapDeps<F, { BASE + $i * <Bc as Catalog>::LEN }>>::Out,)* $($pad,)*);
        }
    };
}
dataflow_macros::cat_leaf!(product_leaf);

macro_rules! product_inner {
    ([$($K:ident $L:ident $pre:tt)*]) => {
        impl<Bc: Catalog, $($K: Catalog,)*> Catalog for Product<($($K,)*), Bc> {
            const LEN: usize = (0 $(+ <$K as Catalog>::LEN)*) * <Bc as Catalog>::LEN;
        }
        impl<F, const BASE: usize, Bc: Catalog, $($K: Catalog,)*> MapDeps<F, BASE> for Product<($($K,)*), Bc>
        where
            $(Product<$K, Bc>: MapDeps<F, { BASE + $pre * <Bc as Catalog>::LEN }>,)*
        {
            type Out = ($(<Product<$K, Bc> as MapDeps<F, { BASE + $pre * <Bc as Catalog>::LEN }>>::Out,)*);
        }
    };
}
dataflow_macros::cat_inner!(product_inner);
