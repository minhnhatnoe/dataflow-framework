//! Subscriptions written as enum patterns (`Some(Btc(t)): Ws`): sugar over the
//! selector chains of the `=>` form. Values, firing on the right variant,
//! nesting, `Option` / `Result`, markers shared by two enums, a generic
//! selector, and equality with the `=>` form. No `#![feature]` here.

use std::marker::PhantomData;
use std::sync::Mutex;

use dataflow_flat::{Component, ComponentSubscription, Configs, Demux, Pipeline, Root, Select};

static LOG: Mutex<Vec<&'static str>> = Mutex::new(Vec::new());
static SERIAL: Mutex<()> = Mutex::new(());
static SEEN: Mutex<Vec<(&'static str, u32)>> = Mutex::new(Vec::new());

fn take() -> Vec<&'static str> {
    std::mem::take(&mut *LOG.lock().unwrap())
}
fn log(s: &'static str) {
    LOG.lock().unwrap().push(s);
}
fn seen() -> Vec<(&'static str, u32)> {
    std::mem::take(&mut *SEEN.lock().unwrap())
}

macro_rules! comp {
    ($name:ident, [$($sub:tt)*], $out:ty, |$i:ident| $body:expr) => {
        #[derive(ComponentSubscription)]
        #[subscribe($($sub)*)]
        pub struct $name;
        impl Component for $name {
            type Config = ();
            type Output = $out;
            fn new((): (), _: Self::Init<'_>) -> (Self, $out) {
                ($name, Default::default())
            }
            fn update(&mut self, $i: Self::Input<'_>) -> $out {
                log(stringify!($name));
                $body
            }
        }
    };
}

// ---------------------------------------------------------------------------
// One level, and equality with the `=>` form
// ---------------------------------------------------------------------------

#[derive(Root, Demux)]
pub enum Pkt {
    A(u32),
    B(u32),
    Tick,
}

mod one {
    use super::*;
    comp!(PatA, [Pkt::A(p): Pkt], u32, |i| {
        SEEN.lock().unwrap().push(("PatA", *i.p));
        *i.p * 10
    });
    comp!(ArrowA, [p: Pkt => pkt::A], u32, |i| {
        SEEN.lock().unwrap().push(("ArrowA", *i.p));
        *i.p * 10
    });
    // a leading path
    comp!(PatB, [super::Pkt::B(p): Pkt], u32, |i| *i.p * 100);
    comp!(All, [a: PatA, b: PatB, c: ArrowA], (u32, u32, u32), |i| (*i.a, *i.b, *i.c));
}

#[test]
fn fires_only_on_its_variant_and_equals_the_arrow_form() {
    let _g = SERIAL.lock().unwrap();
    let mut p = Pipeline::<Pkt, (one::All,)>::build(Configs::new()).unwrap();
    take();
    p.push(Pkt::A(3));
    assert_eq!(take(), ["PatA", "ArrowA", "All"]);
    assert_eq!(seen(), [("PatA", 3), ("ArrowA", 3)]);
    p.push(Pkt::B(2));
    assert_eq!(take(), ["PatB", "All"]);
    p.push(Pkt::Tick);
    assert_eq!(take(), Vec::<&str>::new());
    p.push(Pkt::A(5));
    assert_eq!(take(), ["PatA", "ArrowA", "All"]);
    assert_eq!(seen(), [("PatA", 5), ("ArrowA", 5)]);
}

// ---------------------------------------------------------------------------
// Nesting through Option, with a marker module generated by Demux
// ---------------------------------------------------------------------------

#[derive(Clone, Copy, Debug, PartialEq, Demux)]
pub enum Frame {
    Btc(u32),
    Eth(u32),
}

#[derive(Root)]
pub struct Msg {
    v: Option<Frame>,
}

mod nested {
    use super::*;
    comp!(Parse, [m: Msg], Option<Frame>, |i| i.m.v);
    comp!(Quoter, [Some(Frame::Btc(t)): Parse], u32, |i| *i.t + 1);
    comp!(EthQ, [Some(Frame::Eth(t)): Parse], u32, |i| *i.t + 2);
    comp!(NoneQ, [None(n): Parse], u32, |_i| 0);
}

#[test]
fn nested_option_and_variant() {
    let _g = SERIAL.lock().unwrap();
    comp!(Both, [a: nested::Quoter, b: nested::EthQ], (u32, u32), |i| (*i.a, *i.b));
    let mut p = Pipeline::<Msg, (Both,)>::build(Configs::new()).unwrap();
    take();
    p.push(Msg { v: Some(Frame::Btc(1)) });
    assert_eq!(take(), ["Parse", "Quoter", "Both"]);
    p.push(Msg { v: Some(Frame::Eth(1)) });
    assert_eq!(take(), ["Parse", "EthQ", "Both"]);
    p.push(Msg { v: None });
    assert_eq!(take(), ["Parse"]);
}

// ---------------------------------------------------------------------------
// Result
// ---------------------------------------------------------------------------

#[derive(Root)]
pub struct Res {
    v: Result<u32, u32>,
}

mod res {
    use super::*;
    #[derive(ComponentSubscription)]
    #[subscribe(r: Res)]
    pub struct Parse;
    impl Component for Parse {
        type Config = ();
        type Output = Result<u32, u32>;
        fn new((): (), _: Self::Init<'_>) -> (Self, Self::Output) {
            (Parse, Ok(0))
        }
        fn update(&mut self, i: Self::Input<'_>) -> Self::Output {
            log("Parse");
            i.r.v
        }
    }
    comp!(Good, [Ok(v): Parse], u32, |i| *i.v + 1);
    comp!(Bad, [Err(e): Parse], u32, |i| *i.e + 1000);
    comp!(Join, [g: Good, b: Bad], (u32, u32), |i| (*i.g, *i.b));
}

#[test]
fn result_ok_and_err() {
    let _g = SERIAL.lock().unwrap();
    let mut p = Pipeline::<Res, (res::Join,)>::build(Configs::new()).unwrap();
    take();
    p.push(Res { v: Ok(4) });
    assert_eq!(take(), ["Parse", "Good", "Join"]);
    p.push(Res { v: Err(7) });
    assert_eq!(take(), ["Parse", "Bad", "Join"]);
}

// ---------------------------------------------------------------------------
// Markers shared by two enums, and a generic selector
// ---------------------------------------------------------------------------

pub mod markets {
    pub struct Btc;
    pub struct Eth;
}

#[derive(Clone, Copy, Debug, PartialEq, Demux)]
#[demux(markers = markets)]
pub enum BinanceFrame {
    Btc(u32),
    Eth(u32),
}

#[derive(Clone, Copy, Debug, PartialEq, Demux)]
#[demux(markers = crate::markets)]
pub enum CoinbaseFrame {
    Btc(u32),
    Eth(u32),
}

#[derive(Root)]
pub struct Both2 {
    b: Option<BinanceFrame>,
    c: Option<CoinbaseFrame>,
}

mod shared {
    use super::markets::{Btc, Eth};
    use super::*;
    comp!(Bin, [i: Both2], Option<BinanceFrame>, |i| i.i.b);
    comp!(Coin, [i: Both2], Option<CoinbaseFrame>, |i| i.i.c);
    // the same marker `Btc` selects from both enums
    comp!(BinBtc, [Some(Btc(t)): Bin], u32, |i| *i.t);
    comp!(CoinBtc, [Some(Btc(t)): Coin], u32, |i| *i.t + 100);
    // `Type::Variant` names the same shared marker through the enum
    comp!(BinEth, [Some(BinanceFrame::Eth(t)): Bin], u32, |i| *i.t);
    comp!(CoinEth, [Some(Eth(t)): Coin], u32, |i| *i.t);

    // generic: the selector is a type parameter
    #[derive(ComponentSubscription)]
    #[subscribe(Some(S(t)): Bin)]
    pub struct GenReader<S: Select<BinanceFrame, Out = u32>> {
        _p: PhantomData<S>,
    }
    impl<S: Select<BinanceFrame, Out = u32>> Component for GenReader<S> {
        type Config = ();
        type Output = u32;
        fn new((): (), _: Self::Init<'_>) -> (Self, u32) {
            (GenReader { _p: PhantomData }, 0)
        }
        fn update(&mut self, i: Self::Input<'_>) -> u32 {
            log(std::any::type_name::<S>().rsplit("::").next().unwrap());
            *i.t * 2
        }
    }
    // Bin and Coin both fire on every push, so each pair is joined in its own pipeline.
    comp!(SinkBin, [a: BinBtc, c: BinEth], (u32, u32), |i| (*i.a, *i.c));
    comp!(SinkCoin, [b: CoinBtc, d: CoinEth], (u32, u32), |i| (*i.b, *i.d));
    comp!(SinkGen, [g: GenReader<Btc>, h: GenReader<Eth>], (u32, u32), |i| (*i.g, *i.h));
}

#[test]
fn shared_markers_through_both_spellings() {
    let _g = SERIAL.lock().unwrap();
    let mut p = Pipeline::<Both2, (shared::SinkBin,)>::build(Configs::new()).unwrap();
    take();
    p.push(Both2 { b: Some(BinanceFrame::Btc(1)), c: Some(CoinbaseFrame::Eth(9)) });
    assert_eq!(take(), ["Bin", "BinBtc", "SinkBin"]);
    p.push(Both2 { b: Some(BinanceFrame::Eth(3)), c: None });
    assert_eq!(take(), ["Bin", "BinEth", "SinkBin"]);
    p.push(Both2 { b: None, c: None });
    assert_eq!(take(), ["Bin"]);

    let mut p = Pipeline::<Both2, (shared::SinkCoin,)>::build(Configs::new()).unwrap();
    take();
    p.push(Both2 { b: Some(BinanceFrame::Btc(1)), c: Some(CoinbaseFrame::Eth(9)) });
    assert_eq!(take(), ["Coin", "CoinEth", "SinkCoin"]);
    p.push(Both2 { b: None, c: Some(CoinbaseFrame::Btc(2)) });
    assert_eq!(take(), ["Coin", "CoinBtc", "SinkCoin"]);
}

#[test]
fn generic_selector() {
    let _g = SERIAL.lock().unwrap();
    let mut p = Pipeline::<Both2, (shared::SinkGen,)>::build(Configs::new()).unwrap();
    take();
    p.push(Both2 { b: Some(BinanceFrame::Btc(1)), c: None });
    assert_eq!(take(), ["Bin", "Btc", "SinkGen"]);
    p.push(Both2 { b: Some(BinanceFrame::Eth(3)), c: None });
    assert_eq!(take(), ["Bin", "Eth", "SinkGen"]);
}
